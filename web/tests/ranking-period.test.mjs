import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {previousRankingPeriod,applyRankingPeriod,renderRankingTable,sortRankingReport} from '../dist/leadership-report.js';
const periods=[{id:'m1',type:'month',year:2026,value:1},{id:'m12',type:'month',year:2025,value:12},{id:'m3',type:'month',year:2026,value:3},{id:'q1',type:'quarter',year:2026,value:1},{id:'q4',type:'quarter',year:2025,value:4},{id:'y',type:'year',year:2026}];
assert.equal(previousRankingPeriod(periods,'m1').id,'m12');
assert.equal(previousRankingPeriod(periods,'q1').id,'q4');
assert.equal(previousRankingPeriod(periods,'m3'),undefined,'never skip a missing adjacent period');
assert.equal(previousRankingPeriod(periods,'y'),undefined,'annual daily behavior unchanged');
const row=(id,total,rank)=>({id,name:id,total,totalRank:rank,scores:[total],ranks:[rank]});
const base={period:'Tháng 8/2026',rows:[row('a',60,2),row('b',70,1),row('c',50,3)],notes:[],groupLabels:['Nhóm'],selectedId:'a',nameHeader:'Cơ quan'};
const current={...base,period:'Tháng 9/2026',rows:[row('a',80,1),row('b',70,2),row('c',50,3)]};
const copy=JSON.stringify([current,base]);
const result=applyRankingPeriod(current,base);
assert.equal(result.rows[0].totalRankChange,1);
assert.equal(result.rows[1].totalRankChange,-1);
assert.equal(result.rows[2].totalRankChange,0);
assert.equal(result.rows[0].totalChange,20);
assert.deepEqual(result.rows[0].scoreChanges,[20]);
assert.equal(JSON.stringify([current,base]),copy,'no mutation of either period');
const html=renderRankingTable(result,['transparency'],(value,id,group)=>`<button data-id="${id}" data-group="${group}">${value}</button>`);
assert.match(html,/▲ 1/);assert.match(html,/▼ 1/);assert.match(html,/ranking-up/);assert.match(html,/ranking-down/);
assert.match(html,/data-id="a"/,'score drilldown renderer retained');
assert.equal(sortRankingReport(result,{index:0,direction:'asc'}).rows.at(-1).totalRankChange,1);
const changed=applyRankingPeriod(current,{...base,rows:base.rows.slice(0,2)});
assert.ok(changed.rows.every(r=>r.totalRankChange===null));
assert.equal(changed.rows[0].totalChange,20,'score differences survive cohort change');
const missing=applyRankingPeriod(current,{...base,rows:[]});
assert.ok(missing.rows.every(r=>r.totalChange===null&&r.totalRankChange===null));
const ties=applyRankingPeriod({...current,rows:[row('a',70,1),row('b',70,1),row('c',50,3)]},base);
assert.equal(ties.rows[0].totalRankChange,1);assert.equal(ties.rows[1].totalRankChange,0);
const app=readFileSync(new URL('../src/app.ts',import.meta.url),'utf8');
assert.match(app,/if\(chosen.type!=='year'\)void loadRankingBaseline\(\)/);
assert.match(app,/rankingPeriod\(\).type!=='year'\)\{await loadRankingPeriod\(\);return;\}/);
console.log('RANKING_PERIOD_PASS: adjacent month/quarter, year rollover, no skip, unchanged annual, movement/ties/null/cohort, no mutation, sorting/drilldown');
