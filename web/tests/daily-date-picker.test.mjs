import assert from 'node:assert/strict';
import {selectableDays,renderDatePicker,renderCalendarMonth,bindDatePickers} from '../dist/daily-date-picker.js';
const dates=['2026-10-06','2026-10-07','2026-10-09','2026-10-12'];
assert.deepEqual(selectableDays(dates,'baseline','2026-10-09'),dates.slice(0,2));
assert.deepEqual(selectableDays(dates,'current','2026-10-07'),dates.slice(2));
assert.deepEqual(selectableDays([...dates,...dates],'baseline',null),dates);
assert.match(renderDatePicker('baseline','2026-10-07',dates,'2026-10-12'),/07\/10\/2026/);
assert.match(renderDatePicker('baseline','2026-10-05',['2026-10-06'],'2026-10-06'),/data-calendar-open[^>]*disabled/);
const month=renderCalendarMonth('2026-10',dates,'2026-10-07');
assert.equal([...month.matchAll(/data-calendar-day=/g)].length,31);
assert.match(month,/data-calendar-day="2026-10-08"[^>]*disabled/);
assert.doesNotMatch(month,/data-calendar-day="2026-10-06"[^>]*disabled/);
assert.match(month,/data-calendar-day="2026-10-07"[^>]*aria-pressed="true"/);
assert.equal([...renderCalendarMonth('2028-02',['2028-02-29'],null).matchAll(/data-calendar-day=/g)].length,29);
// DOM adapter: opening, choosing an available day and outside-dismissal do not fetch.
const events={},panelEvents={},docEvents={};let fired=0,focus=0;
const input={value:'2026-10-07',dispatchEvent(e){assert.equal(e.type,'change');fired++}};
const opener={attrs:{},setAttribute(k,v){this.attrs[k]=v},addEventListener(k,f){events['open:'+k]=f},focus(){focus++}};
const panel={hidden:true,innerHTML:'',contains(){return true},querySelector(){return {focus(){focus++}}},addEventListener(k,f){panelEvents[k]=f}};
const root={dataset:{calendarDates:JSON.stringify(dates)},querySelector(s){return s==='[data-daily-indicator-date]'?input:s==='[data-calendar-open]'?opener:panel},contains(target){return target===input||target===panel||target===opener},addEventListener(k,f){events[k]=f}};
const doc={activeElement:panel,querySelectorAll(s){return s==='[data-daily-calendar]'?[root]:s==='[data-calendar-panel]'?[panel]:[opener]},addEventListener(k,f){docEvents[k]=f},removeEventListener(k){delete docEvents[k]}};
const cleanup=bindDatePickers(doc);
events['open:click']();assert.equal(panel.hidden,false);assert.equal(opener.attrs['aria-expanded'],'true');assert.match(panel.innerHTML,/Tháng 10/);
const click=button=>panelEvents.click({target:{closest(){return button}}});
click({disabled:true,dataset:{calendarDay:'2026-10-08'}});assert.equal(fired,0);
click({disabled:false,dataset:{calendarDay:'2026-10-09'}});assert.equal(fired,1);assert.equal(input.value,'2026-10-09');assert.equal(panel.hidden,true);assert(focus>0);
events['open:click']();docEvents.pointerdown({target:{}});assert.equal(panel.hidden,true);
events['open:click']();events.keydown({key:'Escape',preventDefault(){},target:opener});assert.equal(panel.hidden,true);
cleanup();assert.equal(Object.keys(docEvents).length,0,'Global listener removed on panel change');
console.log('DAILY_DATE_PICKER_PASS: dd/mm/yyyy, available days only, strict date ordering, leap month, calendar selection and cleanup');
