import assert from 'node:assert/strict';
import {compareDailyDates,renderDailyDateComparison,historyWithinPeriod} from '../dist/daily-period-comparison.js';
import {annualDailyComparison,annualGroupChange} from '../dist/annual-daily-comparison.js';
const ids=['transparency','dvc-progress-tree','provide-online-tree','dossier-digitized','handling-satisfaction','formality-online-payment-tree'];
const day=(reportDate,score)=>({reportDate,totalScore:score*6,groups:Object.fromEntries(ids.map(id=>[id,{score,maximum:20}]))});
const history={days:[day('2026-10-09',15),day('2026-10-08',12),day('2026-10-07',10),day('2026-10-06',11)]};
const labels=Object.fromEntries(ids.map(id=>[id,id]));
assert.match(annualDailyComparison(history),/\+18,00 điểm/);
assert.match(annualDailyComparison(history,'2026-10-07'),/\+30,00 điểm/);
for(const id of ids)assert.equal(annualGroupChange(history,id,'2026-10-07'),5);
const dates={current:'2026-10-08',baseline:'2026-10-06'};
assert.equal(compareDailyDates(history,dates).current.totalScore,72);
const html=renderDailyDateComparison(history,ids,labels,dates);
assert.match(html,/08\/10\/2026/);assert.match(html,/06\/10\/2026/);
assert.match(html,/\+6,00/);assert.equal((html.match(/\+1,00/g)||[]).length,6);
assert.equal((html.match(/type="date"/g)||[]).length,2);
assert.match(renderDailyDateComparison(history,ids,labels,{current:'2026-10-06',baseline:'2026-10-08'}),/-6,00/);
assert.match(renderDailyDateComparison(history,ids,labels,{current:'2026-10-08',baseline:'2026-10-08'}),/\+0,00/);
const missing=renderDailyDateComparison(history,ids,labels,{current:'2026-10-05',baseline:'2026-10-06'});
assert.match(missing,/Ngày được chọn chưa có dữ liệu/);assert.doesNotMatch(missing,/\+0,00/);
assert.match(renderDailyDateComparison(null,ids,labels),/Chưa có lịch sử/);
const periodHistory={days:['2025-12-31','2026-09-30','2026-10-01','2026-10-31','2026-11-01','2026-12-31','2027-01-01'].map(date=>day(date,10))};
assert.deepEqual(historyWithinPeriod(periodHistory,{type:'month',year:2026,value:10}).days.map(d=>d.reportDate),['2026-10-01','2026-10-31']);
assert.deepEqual(historyWithinPeriod(periodHistory,{type:'quarter',year:2026,value:4}).days.map(d=>d.reportDate),['2026-10-01','2026-10-31','2026-11-01','2026-12-31']);
assert.equal(historyWithinPeriod(periodHistory,{type:'year',year:2026}).days.length,5);
const november=historyWithinPeriod(periodHistory,{type:'month',year:2026,value:11});
assert.match(renderDailyDateComparison(november,ids,labels),/min="2026-11-01" max="2026-11-01"/);
console.log('DAILY_DATE_COMPARISON_PASS: latest 09 vs 07; historical 08 vs 06; all six groups, reverse, equal, gaps, dd/mm/yyyy');
