import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {accountPageQuery,accountPageSummary,accountPager} from '../dist/admin-account-filters.js';
const query=new URLSearchParams(accountPageQuery(3,'  Nguyễn & 100%  ','province','unit','locked'));
assert.deepEqual(Object.fromEntries(query),{page:'3',search:'Nguyễn & 100%',provinceId:'province',unitId:'unit',status:'locked'});
assert.equal(accountPageQuery(1,'','','',''),'page=1');
assert.equal(accountPageSummary(1,25,521),'Hiển thị 1–10 / 25 tài khoản · Tổng toàn hệ thống: 521');
assert.match(accountPageSummary(3,25,521),/21–25 \/ 25/);
assert.match(accountPageSummary(1,0,521),/Hiển thị 0 \/ 0/);
assert.match(accountPager(1,25),/data-account-page="0" disabled/);
assert.match(accountPager(3,25),/data-account-page="4" disabled/);
assert.match(accountPager(2,25),/Trang 2\/3/);
assert.match(accountPager(1,0),/Trang 1\/1/);
const source=readFileSync(new URL('../src/admin.ts',import.meta.url),'utf8');
assert.match(source,/admin\/accounts\?page=1/);
assert.match(source,/sequence!==accountRead/,'Late responses cannot replace current filters');
assert.match(source,/account-status/);assert.match(source,/loadAccountPage\(1\)/,'Filters reset to first page');
assert.match(source,/loadAccountPage\(Number\(button.dataset.accountPage\)\)/);
assert.match(source,/250\)/,'Typing is debounced');
assert.match(source,/data-edit/);assert.match(source,/data-add-credit/);assert.match(source,/data-activate-trial/);
assert.doesNotMatch(source,/filterAdminAccounts\(accounts/,'Server filters all accounts, not just current page');
console.log('ADMIN_ACCOUNTS_PAGINATION_PASS: 10/page, totals/ranges, statuses, combined encoded filters, bounds, debounce, stale-response guard, existing actions retained');
